#!/usr/bin/env python3
"""Generate the submission programme from the same lessons as the working plan."""
import json
from collections import Counter
from pathlib import Path
from docx_layout import paragraph, heading, subheading, pagebreak, table, save

ROOT=Path(__file__).resolve().parents[1]
PROGRAM=json.loads((ROOT/'data/program.json').read_text())
LESSONS=json.loads((ROOT/'data/lessons.json').read_text())
AUTHOR=PROGRAM['author'];YEAR=PROGRAM['academic_year']
COUNT=len(LESSONS);HOURS=sum(l['academic_hours']for l in LESSONS)
MINUTES=sum(l['minutes']for l in LESSONS)
requirement=(COUNT==PROGRAM['expected_lessons'] and all(l['minutes']==PROGRAM['lesson_minutes']for l in LESSONS))
assert requirement,'Programme settings and lessons disagree'
MD=[]


def p(text='',**kwargs):
    paragraph(text,**kwargs)
    if text:MD.extend([text,''])


def h(text):
    heading(text);MD.extend(['## '+text,''])


def s(text):
    subheading(text);MD.extend(['### '+text,''])


def t(rows,widths,size=11):
    table(rows,widths,size=size)
    MD.append('| '+' | '.join(map(str,rows[0]))+' |')
    MD.append('| '+' | '.join('---'for _ in rows[0])+' |')
    MD.extend('| '+' | '.join(str(c).replace('|','/')for c in r)+' |'for r in rows[1:])
    MD.append('')


MD.extend(['# Дополнительная общеобразовательная общеразвивающая программа',''])
for text in ['МИНИСТЕРСТВО НАУКИ И ВЫСШЕГО ОБРАЗОВАНИЯ','РОССИЙСКОЙ ФЕДЕРАЦИИ',
             'ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ АВТОНОМНОЕ','ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ ВЫСШЕГО ОБРАЗОВАНИЯ',
             'Национальный исследовательский ядерный университет "МИФИ"','(НИЯУ МИФИ)']:
    p(text,style='Cover',size=11,after=20)
p(PROGRAM['institution'],style='Cover',size=14,bold=True,after=250)
for text in ['"Согласовано"','Руководитель Лицея 1511','Предуниверситария НИЯУ МИФИ',
             '________________ / __________________','"___" __________________ 2026 г.']:
    p(text,style='Cover',align='right',size=11,after=40)
p('ДОПОЛНИТЕЛЬНАЯ ОБЩЕОБРАЗОВАТЕЛЬНАЯ',style='Cover',bold=True,size=14,before=440,after=70)
p('ОБЩЕРАЗВИВАЮЩАЯ ПРОГРАММА',style='Cover',bold=True,size=14,after=260)
p('Кружок олимпиадной математики',style='Cover',bold=True,size=16,after=100)
p('Подготовка к ВсОШ и МОШ',style='Cover',bold=True,size=14,after=100)
p('10-е классы',style='Cover',bold=True,size=14,after=220)
for text in ['Направленность: '+PROGRAM['direction'],
             'Возраст обучающихся: '+PROGRAM['age']+' (10-е классы)',
             'Срок реализации: один учебный год',YEAR+' учебный год',
             f'Объём: {HOURS} академических часов, {COUNT} занятия',
             'Режим занятий: по субботам, 1 пара (90 минут)']:
    p(text,style='Cover',after=100)
p('Составитель (разработчик): учитель математики',style='Cover',align='right',before=150,after=80)
p(AUTHOR,style='Cover',align='right',bold=True,after=320)
p('Москва, 2026',style='Cover')

pagebreak();h('ПОЯСНИТЕЛЬНАЯ ЗАПИСКА')
p(f'Дополнительная общеобразовательная общеразвивающая программа "{PROGRAM["title"]}" предназначена для обучающихся 10-х классов и реализуется в {YEAR} учебном году. Программа дополняет школьный курс математики и ориентирована на развитие личностных, метапредметных и предметных результатов среднего общего образования.')
p('Актуальность программы связана с необходимостью систематической подготовки к олимпиадным задачам, требующим самостоятельного поиска и строгого обоснования. Уверенное владение школьной алгеброй не заменяет опыта комбинаторных рассуждений, арифметических доказательств и синтетической геометрии. Поэтому эти направления и культура доказательства получают преимущественное внимание.')
p('Основу учебного материала составляют официальные задачи регионального этапа Всероссийской олимпиады школьников по математике для 10 класса. Задачи муниципального этапа вводят основные приёмы и позволяют постепенно наращивать сложность. Задачи Московской олимпиады школьников по математике используются для закрепления методов и их переноса на новые условия.')
p('Отбор задач учитывает уровень группы, наличие доступного метода решения и возможность содержательной работы в пределах одной пары. Подготовка строится от коротких рассуждений и простых моделей к смешанным задачам, учебным турам и самостоятельной защите решений. Темы повторяются при разборе ошибок и применении ранее изученных методов.')
h('ЦЕЛИ ИЗУЧЕНИЯ КУРСА')
p('Цель курса - развить математическое мышление и научить обучающихся самостоятельно искать подход к нестандартной задаче, строить полное доказательство и осознанно выбирать задачи олимпиадного тура.')
for n,text in enumerate(['Освоить основные методы теории чисел, комбинаторики, графов и синтетической геометрии, расширить применение школьной алгебры.',
                        'Научиться исследовать примеры, формулировать гипотезы, строить контрпримеры и проверять все условия задачи.',
                        'Развить умение разделять оценку и достижимость, объяснять ключевые переходы и оформлять проверяемое письменное решение.',
                        'Приобрести опыт самостоятельной работы, распределения времени, разбора критериев и исправления ошибок.'],1):
    p(f'{n}. {text}',style='ListText')

pagebreak();h('МЕСТО КРУЖКА В УЧЕБНОМ ПЛАНЕ')
p(f'Программа рассчитана на один учебный год и включает {COUNT} занятия по 90 минут, что составляет {HOURS} академических часов по 45 минут и {MINUTES//60} астрономический час. Занятия проводятся один раз в неделю по субботам, по одной паре. Форма обучения - очная.')
p('Программа адресована обучающимся 10-х классов, интересующимся олимпиадной математикой. Школьная алгебра используется как исходная подготовка. Объём домашней работы регулируется по результатам диагностики; дополнительные трудные задачи не изменяют обязательную продолжительность курса.')
p('Календарно-тематический план охватывает период с сентября по май. Конкретные даты определяются учебным графиком лицея. Тренировочные туры располагаются до соответствующих олимпиадных этапов; при уточнении сроков допускается перестановка соседних занятий с сохранением содержания и общего количества часов.')
h('ТЕМАТИЧЕСКОЕ ПЛАНИРОВАНИЕ')
counts=Counter(l['block']for l in LESSONS)
sections=[(v['title'],counts[k])for k,v in PROGRAM['blocks'].items()]
rows=[['Название раздела','Количество академических часов']]
rows.extend([title,count*2]for title,count in sections)
rows.append(['Итого',HOURS]);t(rows,[7355,2000])

pagebreak();h('СОДЕРЖАНИЕ ПРОГРАММЫ')
for block,details in PROGRAM['blocks'].items():
    s(details['title']+f' ({counts[block]*2} часов)')
    p(details['content'])

for start,stop in [(0,11),(11,23),(23,34)]:
    pagebreak();h('КАЛЕНДАРНО-ТЕМАТИЧЕСКИЙ ПЛАН')
    if start==0:p('Одна строка соответствует одной субботней паре. Объём каждого занятия - 2 академических часа, продолжительность - 90 минут.',style='Caption',size=11)
    rows=[['N','Период','Тема занятия','Часы','Основное содержание и учебная деятельность']]
    rows.extend([l['number'],l['month'],l['title'],l['academic_hours'],l['goal']]for l in LESSONS[start:stop])
    t(rows,[450,1050,2800,800,4255],size=10)
    if stop==34:p(f'Итого: {COUNT} занятия, {HOURS} академических часов.',style='Caption',size=11)

pagebreak();h('ПЛАНИРУЕМЫЕ РЕЗУЛЬТАТЫ ОСВОЕНИЯ ПРОГРАММЫ')
s('Личностные результаты')
for text in ['Устойчивый интерес к математическому исследованию и решению нестандартных задач.',
             'Самостоятельность и готовность доводить рассуждение до доказательства, принимать обратную связь и исправлять ошибки.',
             'Ответственность за результат собственной работы, уважение к чужим идеям и честность при выполнении самостоятельных заданий.',
             'Готовность сотрудничать, обсуждать различные подходы и сохранять настойчивость при столкновении с трудной задачей.']:
    p(text,style='ListText')
h('МЕТАПРЕДМЕТНЫЕ РЕЗУЛЬТАТЫ')
for text in ['Познавательные действия: выделение данных и требований задачи, построение модели, поиск закономерности, выдвижение и проверка гипотез, применение анализа, сравнения, дедукции и индукции.',
             'Коммуникативные действия: ясное устное и письменное изложение идеи, объяснение ключевых переходов, обсуждение доказательства, формулирование содержательных вопросов и аргументированных возражений.',
             'Регулятивные действия: планирование поиска, распределение времени, самопроверка, выявление недостатков решения, корректировка способа действия и оценка собственного продвижения.']:
    p(text)
h('ПРЕДМЕТНЫЕ РЕЗУЛЬТАТЫ')
for text in ['В теории чисел обучающийся использует остатки, делимость, взаимную простоту, разложение на множители и показатели простых делителей для обоснования целочисленных ограничений.',
             'В комбинаторике обучающийся применяет оценки и конструкции, инварианты, крайний элемент, двойной подсчёт, индукцию и соответствия; строит графовую модель и обосновывает игровую или информационную стратегию.',
             'В геометрии обучающийся применяет углы и окружности, дополнительные построения, симметрию, площади, проекции, подобие и степень точки; проверяет условия равенства в геометрической оценке.',
             'В алгебре обучающийся использует свойства многочленов, теорему Виета и связь коэффициентов с делимостью значений; выбирает преобразование, сокращающее доказательство.',
             'Общий предметный результат - выбор подходящего метода и логически завершённое доказательство с проверкой случаев, конструкции и достижения экстремальной границы.']:
    p(text,style='ListText')

pagebreak();h('ОРГАНИЗАЦИЯ ОБУЧЕНИЯ И ОЦЕНКА РЕЗУЛЬТАТОВ')
s('Формы и методы работы')
p('Используются краткое объяснение метода, индивидуальный поиск решения, обсуждение в парах и малых группах, работа у доски, письменные тренировочные туры и защита решений. Обычная пара включает 10 минут повторения, 15 минут введения метода, 35 минут поиска, 20 минут записи и обсуждения, 10 минут обратной связи.')
p('В тренировочных турах предусмотрено 75 минут самостоятельной работы и 15 минут самооценки. Полный официальный лист используется для обучения выбору задач; решение всех его номеров в сокращённое время не предполагается. Продолжительность учебной работы не объявляется продолжительностью официального олимпиадного тура.')
p('Домашняя работа обычно предполагает 30-60 минут самостоятельной попытки и оформления результата. Трудные дополнительные задачи могут выполняться с направляющей подсказкой и последующим разбором. После самостоятельной попытки допускается изучение опубликованного решения с его последующим воспроизведением и объяснением.')
s('Формы контроля')
p('Входной контроль проводится на первом занятии. Текущий контроль включает обсуждение подходов, проверку письменных решений и индивидуальную обратную связь. Промежуточный контроль проводится в муниципальном, региональных и московском тренировочных турах. Итоговая оценка включает смешанную самостоятельную работу и защиту исправленных решений.')
p('Оцениваются правильность, полнота доказательства, самостоятельность и качество оформления. Для олимпиадной задачи используются опубликованные критерии соответствующего комплекта. Результаты сокращённой учебной работы не сравниваются напрямую с официальными проходными баллами. Обучающийся фиксирует законченные решения, пропущенные случаи и дальнейшие действия.')
p('К концу курса обучающийся готовит не менее двух самостоятельно объяснённых решений по каждому из четырёх основных разделов, исправляет письменные работы после проверки и составляет личную карту освоенных методов и типичных ошибок.')
s('Условия реализации')
p('Необходимы учебный кабинет, доска, письменные принадлежности, раздаточные материалы и возможность подготовки печатных листов задач. Проектор используется при необходимости. Основные задания выполняются с письменным обоснованием; рисунки и формулы берутся из официальных материалов.')
h('УЧЕБНО-МЕТОДИЧЕСКОЕ ОБЕСПЕЧЕНИЕ')
for n,text in enumerate(['Официальные задания и решения регионального этапа Всероссийской олимпиады школьников по математике для 10 класса, 2010-2026 годы. Публикации МЦНМО и организаторов олимпиады.',
                        'Официальные муниципальные задания по математике для 10 класса разных регионов Российской Федерации. Условия, решения и критерии оценивания.',
                        'Официальные задания и решения Московской математической олимпиады для 10 класса, 2011-2026 годы. Публикации оргкомитета олимпиады.',
                        'Методические рекомендации по организации и проведению школьного и муниципального этапов Всероссийской олимпиады школьников по математике в 2026/2027 учебном году.',
                        'Дидактические материалы составителя: тематические подборки, диагностические работы, тренировочные туры и рекомендации по оформлению решений.'],1):
    p(f'{n}. {text}',style='Reference')

OUT=ROOT/'course/План_для_сдачи_2026-2027.docx'
save(OUT,title=PROGRAM['title'],author=AUTHOR,lessons=LESSONS,sections=sections)
(ROOT/'course/submission.md').write_text('\n'.join(MD))
snapshot={'author':AUTHOR,'academic_year':YEAR,'lessons':[{k:l[k]for k in ['number','month','title','minutes','academic_hours','goal','block']}for l in LESSONS],
          'academic_hours':HOURS,'clock_minutes':MINUTES,'section_hours':{k:counts[k]*2 for k in PROGRAM['blocks']}}
(ROOT/'data/submission-map.json').write_text(json.dumps(snapshot,ensure_ascii=False,indent=2)+'\n')
