#!/usr/bin/env python3
"""Build the reference-style submission programme from shared course data."""
import argparse
import json
from collections import Counter
from pathlib import Path
from docx_layout import paragraph, heading, subheading, pagebreak, table, save, run

ROOT=Path(__file__).resolve().parents[1]
PROGRAM=json.loads((ROOT/'data/program.json').read_text())
LESSONS=json.loads((ROOT/'data/lessons.json').read_text())
AUTHOR=PROGRAM['author'];YEAR=PROGRAM['academic_year']
COUNT=len(LESSONS);HOURS=sum(l['academic_hours']for l in LESSONS)
MINUTES=sum(l['minutes']for l in LESSONS)
assert COUNT==PROGRAM['expected_lessons'] and all(l['minutes']==PROGRAM['lesson_minutes']for l in LESSONS),'Programme settings and lessons disagree'
counts=Counter(l['block']for l in LESSONS)
sections=[(v['title'],counts[k])for k,v in PROGRAM['blocks'].items()]
MD=[]


def p(text='',**kwargs):
    node=paragraph(text,**kwargs)
    if text:MD.extend([text,''])
    return node


def h(text):
    heading(text);MD.extend(['## '+text,''])


def s(text):
    subheading(text);MD.extend(['### '+text,''])


def cover_label(label,text,**kwargs):
    node=paragraph('',style='Cover',**kwargs)
    run(node,label,bold=True);run(node,text)
    MD.extend([label+text,''])


MD.extend(['# Дополнительная общеобразовательная общеразвивающая программа',''])
p('МИНИСТЕРСТВО НАУКИ И ВЫСШЕГО ОБРАЗОВАНИЯ РОССИЙСКОЙ ФЕДЕРАЦИИ',style='Cover',size=11,after=160)
p('ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ АВТОНОМНОЕ',style='Cover',size=12,after=0)
p('ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ ВЫСШЕГО ОБРАЗОВАНИЯ',style='Cover',size=12,after=160)
p('Национальный исследовательский ядерный университет "МИФИ"',style='Cover',bold=True,size=13,after=0)
p('(НИЯУ МИФИ)',style='Cover',bold=True,size=13,after=160)
p(PROGRAM['institution'],style='Cover',size=13,bold=True,after=260)
for text in ['"Согласовано"','Руководитель','Лицея 1511','Предуниверситария','НИЯУ МИФИ',
             '________________','________________','"___" ________ 2026 г.']:
    p(text,style='Cover',align='left',left=6500,size=11,after=0)
p('ДОПОЛНИТЕЛЬНАЯ ОБЩЕОБРАЗОВАТЕЛЬНАЯ',style='Cover',size=12,before=600,after=240)
p('ОБЩЕРАЗВИВАЮЩАЯ ПРОГРАММА',style='Cover',size=12,after=300)
cover_label('НАЗВАНИЕ КРУЖКА: ',PROGRAM['title'],before=0,after=0)
p('10 класс',style='Cover',after=480)
cover_label('НАПРАВЛЕННОСТЬ: ',PROGRAM['direction'],after=620)
p('Возраст обучающихся: 10 классы',style='Cover',bold=True,after=200)
p('Срок реализации: один учебный год',style='Cover',after=80)
p(YEAR+' учебный год',style='Cover',after=260)
p('Составитель (разработчик): учитель математики',style='Cover',align='right',after=140)
p(AUTHOR,style='Cover',align='right',bold=True,after=400)
p('г. Москва',style='Cover')

# The supplied reference has a summary of sections, not a lesson calendar.
# Detailed lessons, dates, goals and task assignments stay in the working plan.
pagebreak();h('ПОЯСНИТЕЛЬНАЯ ЗАПИСКА')
p(f'Программа кружка "{PROGRAM["title"]}" предназначена для обучающихся 10-х классов и реализуется в {YEAR} учебном году. Программа дополняет школьный курс математики, поддерживает интерес к математическому исследованию и развивает умение самостоятельно решать нестандартные задачи.')
p('Актуальность программы связана с необходимостью систематической подготовки к олимпиадным задачам, требующим поиска подхода и строгого обоснования. Владение школьной алгеброй дополняется опытом комбинаторных рассуждений, арифметических доказательств и синтетической геометрии. Особое внимание уделяется культуре математического доказательства.')
p('Основу учебного материала составляют официальные задачи регионального этапа Всероссийской олимпиады школьников по математике для 10 класса. Задачи муниципального этапа вводят основные приёмы и позволяют постепенно наращивать сложность. Задачи Московской олимпиады школьников по математике используются для закрепления методов и их переноса на новые условия.')
p('В ходе занятий обучающиеся исследуют примеры, формулируют и проверяют гипотезы, обсуждают различные способы решения и оформляют письменные доказательства. Работа строится от коротких рассуждений и простых моделей к смешанным задачам и тренировочным турам. Повторение методов, разбор ошибок и исправление решений обеспечивают последовательное развитие математического мышления.')

h('ЦЕЛИ ИЗУЧЕНИЯ КУРСА')
p('Кружок олимпиадной математики дополняет основные математические курсы и направлен на более глубокое изучение методов решения нестандартных задач. Цель курса - развить математическое мышление и научить обучающихся самостоятельно искать подход к задаче, строить полное доказательство и осознанно выбирать задачи олимпиадного тура.')
for text in ['Освоение основных методов теории чисел, комбинаторики, графов и синтетической геометрии; расширение применения школьной алгебры.',
             'Развитие исследовательских умений: анализ условия, работа с примерами, выдвижение гипотез, построение контрпримеров и проверка всех случаев.',
             'Формирование навыков строгого рассуждения, ясного устного объяснения и проверяемого письменного оформления решения.',
             'Приобретение опыта самостоятельной работы, распределения времени, обсуждения критериев оценивания и исправления ошибок.']:
    p(text,style='ListText')

h('МЕСТО КРУЖКА В УЧЕБНОМ ПЛАНЕ')
p(f'Кружок проводится в 10-х классах один раз в неделю по субботам, по одной паре продолжительностью {PROGRAM["lesson_minutes"]} минут. Программа рассчитана на {COUNT} занятия в течение одного учебного года. Общий объём составляет {HOURS} академических часов по 45 минут, или {MINUTES//60} астрономический час. Форма обучения - очная.')
p('Курс предназначен для обучающихся, интересующихся олимпиадной математикой и подготовкой к муниципальному и региональному этапам ВсОШ и Московской олимпиаде школьников. Последовательность изучения тем и сроки тренировочных работ уточняются по учебному графику лицея и календарю олимпиад с сохранением общего объёма программы.')

h('ТЕМАТИЧЕСКОЕ ПЛАНИРОВАНИЕ')
p('10 класс',align='center',indent=0,after=100)
rows=[['Название раздела','Кол-во часов']]
rows.extend([title,count*2]for title,count in sections)
rows.append(['Итого',HOURS])
table(rows,[7355,2000],size=12,total=True,shaded=False)
MD.extend(['| Название раздела | Кол-во часов |','| --- | --- |'])
MD.extend('| '+str(title)+' | '+str(hours)+' |'for title,hours in rows[1:]);MD.append('')

h('ПЛАНИРУЕМЫЕ РЕЗУЛЬТАТЫ ОСВОЕНИЯ ПРОГРАММЫ')
p('Личностные результаты освоения программы характеризуются в части:')
for title,text in [
    ('Патриотического воспитания:', 'уважения к достижениям отечественной математической школы, интереса к истории математических идей и традициям российских олимпиад;'),
    ('Гражданского и духовно-нравственного воспитания:', 'ответственного отношения к собственной работе, честности при выполнении самостоятельных заданий, уважения к чужим идеям и готовности к аргументированному обсуждению;'),
    ('Трудового воспитания:', 'самостоятельности, настойчивости в поиске решения, аккуратности при записи доказательства и готовности исправлять допущенные ошибки;'),
    ('Эстетического воспитания:', 'умения видеть красоту и изящество математического рассуждения, геометрической конфигурации, симметрии и короткого доказательства;'),
    ('Ценностей научного познания:', 'интереса к исследованию, готовности проверять гипотезы, различать пример и доказательство, объяснять границы применимости выбранного метода;'),
    ('Физического воспитания, культуры здоровья и эмоционального благополучия:', 'осознанного распределения времени и учебной нагрузки, сохранения работоспособности и спокойного отношения к затруднениям при решении задач;'),
    ('Экологического воспитания:', 'понимания роли математических моделей и количественных оценок в изучении окружающего мира, ответственного отношения к ресурсам и результатам деятельности;'),
    ('Адаптации к изменяющимся условиям:', 'готовности действовать при неопределённости, выбирать доступные задачи, пересматривать неудачный подход и осваивать новые способы рассуждения.')]:
    s(title);p(text)

h('МЕТАПРЕДМЕТНЫЕ РЕЗУЛЬТАТЫ')
p('В результате освоения программы у обучающихся развиваются познавательные, коммуникативные и регулятивные универсальные учебные действия.')
s('Познавательные универсальные учебные действия')
for title,text in [
    ('Базовые логические действия:', 'выделять данные и требования задачи; сравнивать объекты, выявлять закономерности и причинно-следственные связи; применять анализ, синтез, классификацию, дедукцию и индукцию;'),
    ('Базовые исследовательские действия:', 'проводить исследование малых случаев, формулировать гипотезы, строить математическую модель, находить контрпример и проверять полноту доказательства;'),
    ('Работа с информацией:', 'читать математический текст, соотносить формулы и рисунок, выбирать подходящий источник, сопоставлять собственное решение с опубликованным и оценивать обоснованность выводов.')]:
    s(title);p(text)
s('Коммуникативные универсальные учебные действия')
for title,text in [
    ('Общение:', 'ясно излагать идею устно и письменно, объяснять ключевые переходы, задавать содержательные вопросы, аргументировать возражения и корректно обсуждать различные решения;'),
    ('Совместная деятельность:', 'согласовывать способы работы, обсуждать общий план решения, учитывать предложения других участников и оценивать вклад каждого в полученный результат.')]:
    s(title);p(text)
s('Регулятивные универсальные учебные действия')
for title,text in [
    ('Самоорганизация:', 'ставить цель, планировать поиск решения, распределять время и выбирать способ действия с учётом собственных возможностей и имеющихся ресурсов;'),
    ('Самоконтроль и эмоциональный интеллект:', 'проверять промежуточные результаты, находить логические разрывы и пропущенные случаи, исправлять ошибки, оценивать продвижение и сохранять настойчивость при затруднениях.')]:
    s(title);p(text)

h('ПРЕДМЕТНЫЕ РЕЗУЛЬТАТЫ')
for text in ['В теории чисел обучающийся использует остатки, чётность, делимость, взаимную простоту, разложение на множители и показатели простых делителей для обоснования целочисленных ограничений.',
             'В комбинаторике обучающийся применяет оценки и конструкции, инварианты, крайний элемент, двойной подсчёт, индукцию и соответствия; строит графовые модели и обосновывает игровые и информационные стратегии.',
             'В геометрии обучающийся применяет свойства углов и окружностей, дополнительные построения, симметрию, площади, проекции, подобие и степень точки; доказывает геометрические неравенства и проверяет условия равенства.',
             'В алгебре обучающийся использует свойства многочленов, теорему Виета и связь коэффициентов с делимостью значений; выбирает преобразования, сокращающие доказательство.',
             'В рамках всех разделов формируется умение выбирать подходящий метод, строить логически завершённое доказательство, проверять все случаи и обосновывать достижимость найденной оценки.',
             'По результатам тренировочных работ обучающийся сопоставляет собственное решение с критериями, исправляет недостатки и самостоятельно объясняет ключевой приём решения.']:
    p(text)
p('Для реализации программы используются следующие учебные материалы:')
for n,text in enumerate([
    'Официальные задания и решения регионального этапа Всероссийской олимпиады школьников по математике для 10 класса, 2010-2026 годы. Публикации МЦНМО и организаторов олимпиады.',
    'Официальные муниципальные задания по математике для 10 класса разных регионов Российской Федерации. Условия, решения и критерии оценивания.',
    'Официальные задания и решения Московской математической олимпиады для 10 класса, 2011-2026 годы. Публикации оргкомитета олимпиады.',
    'Методические рекомендации по организации и проведению школьного и муниципального этапов Всероссийской олимпиады школьников по математике в 2026/2027 учебном году.'],1):
    p(f'{n}. {text}',style='Reference',size=12)

parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output',type=Path,default=ROOT/'course/План_для_сдачи_2026-2027.docx',help='Write DOCX to this path without overwriting the checked-out plan')
OUT=parser.parse_args().output
save(OUT,title=PROGRAM['title'],author=AUTHOR,lessons=LESSONS,sections=sections,page_numbers=False)
(ROOT/'course/submission.md').write_text('\n'.join(MD))
snapshot={'author':AUTHOR,'academic_year':YEAR,'lessons':[{k:l[k]for k in ['number','month','title','minutes','academic_hours','goal','block']}for l in LESSONS],
          'academic_hours':HOURS,'clock_minutes':MINUTES,'section_hours':{k:counts[k]*2 for k in PROGRAM['blocks']}}
(ROOT/'data/submission-map.json').write_text(json.dumps(snapshot,ensure_ascii=False,indent=2)+'\n')
