def form(t):
    text = (t['statement_text'] + ' ' + t.get('summary','')).lower()
    if any(x in text for x in ['играют','выигрыш','стратег','может ли игрок','фокусник']): return 'game'
    if any(x in text for x in ['наибольш','наименьш','максимальн','минимальн']): return 'extremum'
    if 'найдите все' in text or 'найти все' in text or 'при каких' in text: return 'classification'
    if any(x in text for x in ['скольк','количество способов','найдите количество']): return 'count'
    if any(x in text for x in ['существу','можно ли','могло ли','может ли','может оказаться']): return 'existence'
    if 'докажите' in text: return 'proof'
    if any(x in text for x in ['найдите','вычислите','найти','найдите угол']): return 'computation'
    return 'other'


def write(path, content):
    target = ROOT / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content.strip() + '\n')


def condition_source(t):
    return next((s for role in ['shared_statement','tasks'] for s in t['sources'] if s['role']==role),t['sources'][0])


def pdf_link(t, label=None, parent='..', solutions=False):
    sources = t['sources']
    s = next((s for role in ['solutions','combined','criteria'] for s in sources if s['role']==role), sources[0]) if solutions else condition_source(t)
    return f"[{label or t['id']}]({parent}/{s['path']}#page={s['page']})"


def problem_line(task_id, parent='..'):
    t = BY_ID[task_id]
    return f"{pdf_link(t, parent=parent)}: {t.get('summary', 'Условие в оригинальном PDF')}."


